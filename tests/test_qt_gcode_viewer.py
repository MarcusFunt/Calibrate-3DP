def _artifact(path: Path, *, sha256: str | None = None) -> ArtifactRecord:
    payload = path.read_bytes()
    return ArtifactRecord(
        path.name,
        "text/x.gcode",
        len(payload),
        sha256 or hashlib.sha256(payload).hexdigest(),
    )


def _wait_for_page_text(dialog: GcodeViewerDialog, expected: str, timeout_ms: int = 30000) -> str:
    result = {"text": ""}
    pending = {"value": False}

    def check():
        if pending["value"]:
            return
        pending["value"] = True
        dialog.page.runJavaScript(
            "document.body ? document.body.innerText : ''",
            0,
            on_text,
        )

    def on_text(value):
        result["text"] = str(value or "")
        pending["value"] = False

    deadline = time.monotonic() + timeout_ms / 1000
    while time.monotonic() < deadline and expected not in result["text"]:
        check()
        APP.processEvents()
        time.sleep(0.02)
    return result["text"]


class QtGcodeViewerTests(unittest.TestCase):
    def tearDown(self):
        for widget in QApplication.topLevelWidgets():
            widget.close()
            widget.deleteLater()
        QApplication.sendPostedEvents(None, QEvent.Type.DeferredDelete)
        QApplication.processEvents()

    def test_supports_gcode_and_sliced_gcode_3mf_names_case_insensitively(self):
        self.assertTrue(supports_gcode_preview("runs/plate.gcode"))
        self.assertTrue(supports_gcode_preview("runs/Plate.GCODE.3MF"))
        self.assertFalse(supports_gcode_preview("runs/manifest.json"))

    def test_webengine_compatibility_is_checked_against_the_project_qt_floor(self):
        capability_check = getattr(gcode_viewer, "qt_webengine_supported", None)
        self.assertIsNotNone(capability_check)
        if capability_check is None:
            return
        self.assertFalse(capability_check("6.7.2"))
        self.assertTrue(capability_check("6.8.0"))
        self.assertTrue(capability_check("6.12.0"))

    def test_dialog_explains_an_unsupported_qt_runtime_without_starting_webengine(self):
        with tempfile.TemporaryDirectory() as temporary:
            path = Path(temporary) / "plate.gcode"
            path.write_bytes(_SAMPLE_GCODE)
            with patch("calibrate3dp.app.qt.gcode_viewer.qt_webengine_supported", return_value=False):
                dialog = GcodeViewerDialog(path, _artifact(path))

            self.assertIn("requires PySide6 6.8", dialog.notice.text())
            self.assertFalse(hasattr(dialog, "view"))

    @unittest.skipUnless(
        gcode_viewer.qt_webengine_supported() if hasattr(gcode_viewer, "qt_webengine_supported") else False,
        "the browser parse test requires the project's supported PySide6 6.8+ runtime",
    )
    def test_upstream_viewer_parses_a_local_orcaslicer_gcode_file(self):
        with tempfile.TemporaryDirectory() as temporary:
            path = Path(temporary) / "plate.gcode"
            path.write_bytes(_SAMPLE_GCODE)
            dialog = GcodeViewerDialog(path, _artifact(path))
            dialog.show()

            page_text = _wait_for_page_text(dialog, "Preview ready")

            self.assertIn("Toolpath segments", page_text)
            self.assertIn("Layers", page_text)
            self.assertIn("Parse coverage", page_text)
            self.assertIn("View mode", page_text)
            self.assertIn("2D layers", page_text)
            self.assertIn("Visual inspection only", page_text)

    @unittest.skipUnless(
        os.environ.get("CALIBRATE3DP_ORCA_GCODE_3MF_FIXTURE")
        and (gcode_viewer.qt_webengine_supported() if hasattr(gcode_viewer, "qt_webengine_supported") else False),
        "requires a retained Orca-sliced package and PySide6 6.8+",
    )
    def test_upstream_viewer_parses_a_retained_orcaslicer_gcode_3mf(self):
        path = Path(os.environ["CALIBRATE3DP_ORCA_GCODE_3MF_FIXTURE"])
        artifact = _artifact(path)
        artifact = ArtifactRecord(
            artifact.relative_path, "model/3mf", artifact.size_bytes, artifact.sha256
        )
        dialog = GcodeViewerDialog(path, artifact)
        dialog.show()

        page_text = _wait_for_page_text(dialog, "Preview ready")

        self.assertIn("Toolpath segments", page_text)
        self.assertIn("Layers", page_text)
        self.assertIn("Parse coverage", page_text)

    @unittest.skipUnless(
        gcode_viewer.qt_webengine_supported() if hasattr(gcode_viewer, "qt_webengine_supported") else False,
        "the browser hash-gate test requires the project's supported PySide6 6.8+ runtime",
    )
    def test_artifact_hash_is_rechecked_before_the_parser_receives_file(self):
        with tempfile.TemporaryDirectory() as temporary:
            path = Path(temporary) / "plate.gcode"
            path.write_bytes(_SAMPLE_GCODE)
            dialog = GcodeViewerDialog(path, _artifact(path, sha256="0" * 64))
            dialog.show()

            page_text = _wait_for_page_text(dialog, "No preview was started")

            self.assertIn("Preview unavailable", page_text)
            self.assertTrue(dialog._load_failed)
